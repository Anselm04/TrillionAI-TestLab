import {test} from 'node:test';
import assert from 'node:assert/strict';
import {generateKeyPairSync} from 'node:crypto';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {EvidenceLedger,verifyEvidenceLedger} from '../src/evidence-ledger.js';
test('signed persistent ledger detects alteration, deletion, reorder and rollback',async t=>{
 const dir=await mkdtemp(join(tmpdir(),'evidence-chain-')),path=join(dir,'ledger.db');
 const keys=generateKeyPairSync('ed25519'),other=generateKeyPairSync('ed25519');
 let ledger=new EvidenceLedger(path,{privateKey:keys.privateKey,maxEntries:3});
 t.after(async()=>{ledger.close();await rm(dir,{recursive:true,force:true});});
 const record=runId=>({runId,manifestSha256:'a'.repeat(64),reviewSha256:'b'.repeat(64)});
 ledger.append(record('run-1'));ledger.append(record('run-2'));
 const checkpoint=ledger.checkpoint();
 ledger.close();ledger=new EvidenceLedger(path,{privateKey:keys.privateKey,maxEntries:3});
 assert.throws(()=>ledger.append(record('run-1')));
 ledger.append(record('run-3'));assert.throws(()=>ledger.append(record('run-4')));
 const records=ledger.records();
 const check=(entries,publicKey=keys.publicKey,cp=checkpoint)=>verifyEvidenceLedger({records:entries,publicKey,checkpoint:cp});
 assert.equal(check(records).valid,true);assert.equal(check(records).checkpointVerified,true);
 assert.equal(check(records.slice(0,1)).valid,false);
 assert.equal(check([records[0],records[2]]).valid,false);
 assert.equal(check([records[1],records[0],records[2]]).valid,false);
 const forged=structuredClone(records);forged[1].body.manifestSha256='c'.repeat(64);
 assert.equal(check(forged).valid,false);
 assert.equal(check(records,other.publicKey).valid,false);
 const bad=structuredClone(checkpoint);bad.body.count=1;
 assert.equal(check(records,keys.publicKey,bad).valid,false);
});
