import {test} from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {generateKeyPairSync} from 'node:crypto';
import {ReviewChallengeStore,createReplayProtectedReviewer} from '../src/review-challenges.js';
import {attestMobileRun} from '../src/signed-mobile-review.js';
const context={deviceId:'device-1',buildSha256:'a'.repeat(64),flowSha256:'b'.repeat(64)};
test('challenge expiry, replay and restart persistence',async t=>{
 const dir=await mkdtemp(join(tmpdir(),'testlab-review-'));
 const path=join(dir,'review.db');let now=10000;
 const a=new ReviewChallengeStore(path,{clock:()=>now}),b=new ReviewChallengeStore(path,{clock:()=>now});
 t.after(async()=>{a.close();b.close();await rm(dir,{recursive:true,force:true});});
 const first=a.issue({...context,ttlMs:1000});
 assert.equal(b.expected(first.challengeId).deviceId,context.deviceId);
 assert.equal(b.consume({...first,runId:'run-1',deviceId:'other'}),false);
 assert.equal(a.consume({...first,runId:'run-1'}),true);
 assert.equal(b.expected(first.challengeId),null);
 const next=b.issue(context);
 assert.equal(b.consume({...next,runId:'run-1'}),false);
 assert.equal(b.consume({...next,runId:'run-2'}),true);
 const expired=a.issue({...context,ttlMs:1000});now+=1000;
 assert.equal(b.expected(expired.challengeId),null);
 assert.equal(b.consume({...expired,runId:'run-3'}),false);
});
test('reviewer rejects mismatched challenge and signs only once',async t=>{
 const dir=await mkdtemp(join(tmpdir(),'testlab-review-'));
 const challenges=new ReviewChallengeStore(join(dir,'review.db'));
 t.after(async()=>{challenges.close();await rm(dir,{recursive:true,force:true});});
 const worker=generateKeyPairSync('ed25519'),reviewer=generateKeyPairSync('ed25519');
 const challenge=challenges.issue(context);
 const manifest={...context,runId:'run-1',reviewChallengeId:challenge.challengeId,artifacts:[{kind:'log'},{kind:'screenshot'}]};
 const store={verify:async m=>m===manifest};
 const attestation=await attestMobileRun({report:{...context,status:'COMMAND_SUCCEEDED',evidenceManifest:manifest},store,privateKey:worker.privateKey});
 const review=createReplayProtectedReviewer({challenges,store,workerPublicKey:worker.publicKey,reviewerPrivateKey:reviewer.privateKey});
 await assert.rejects(review({challengeId:challenges.issue(context).challengeId,manifest,attestation}));
 const results=await Promise.allSettled([review({challengeId:challenge.challengeId,manifest,attestation}),review({challengeId:challenge.challengeId,manifest,attestation})]);
 assert.equal(results.filter(x=>x.status==='fulfilled').length,1);
 assert.equal(results.find(x=>x.status==='fulfilled').value.body.decision,'EVIDENCE_ACCEPTED');
 await assert.rejects(review({challengeId:challenge.challengeId,manifest,attestation}));
});
